create policy lezen_ingelogd on folder_runs         for select to authenticated using (true);

-- Controlelijst: ingelogde gebruikers mogen alleen 'reviewed' afvinken.
revoke update on folder_offers from authenticated;
grant update (reviewed) on folder_offers to authenticated;
drop policy if exists controle_ingelogd on folder_offers;
create policy controle_ingelogd on folder_offers for update to authenticated
  using (true) with check (true);

-- ---------- Storage: buckets en policies ----------
-- 'folders': PDF's en paginabeelden (schrijven: service-rol).
-- 'folders-inbox': handmatige upload van PDF's door ingelogde gebruikers.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('folders', 'folders', false, 52428800, null)
on conflict (id) do nothing;
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('folders-inbox', 'folders-inbox', false, 52428800, array['application/pdf'])
on conflict (id) do nothing;

drop policy if exists folders_lezen_ingelogd on storage.objects;
create policy folders_lezen_ingelogd on storage.objects for select to authenticated
  using (bucket_id in ('folders', 'folders-inbox'));
drop policy if exists folders_inbox_upload_ingelogd on storage.objects;
create policy folders_inbox_upload_ingelogd on storage.objects for insert to authenticated
  with check (bucket_id = 'folders-inbox');
